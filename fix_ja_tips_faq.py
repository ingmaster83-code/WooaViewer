ok = 0
skip = 0
err = 0

for fname, d in DATA.items():
    fpath = os.path.join(JA_DIR, fname)
    if not os.path.exists(fpath):
        print(f'  MISSING: {fname}')
        err += 1
        continue

    with open(fpath, 'r', encoding='utf-8') as f:
        content = f.read()

    original = content
    tips = d['tips']
    faq = d['faq']

    # ── Tips 교체 ──────────────────────────────────────────────
    # tips-panel 안의 <ul>...</ul> 블록을 통째로 교체
    new_ul = '<ul>' + ''.join(f'<li>{t}</li>' for t in tips) + '</ul>'
    content = re.sub(
        r'(<div class="tips-panel"><h3>💡 ヒント</h3>)<ul>.*?</ul>',
        r'\1' + new_ul,
        content,
        flags=re.DOTALL,
        count=1
    )

    # ── FAQ Q1/A1 교체 ────────────────────────────────────────
    q1, a1 = faq[0]
    content = re.sub(
        r'<details><summary>.*?</summary><p>.*?</p></details>'
        r'(<details><summary>.*?</summary>)',
        f'<details><summary>{q1}</summary><p>{a1}</p></details>\\1',
        content,
        flags=re.DOTALL,
        count=1
    )

    # ── FAQ Q2/A2 교체 ────────────────────────────────────────
    q2, a2 = faq[1]
    # 두 번째 details: 첫 번째 교체 이후 두 번째로 나오는 details
    def replace_second_details(m):
        return f'<details><summary>{q2}</summary><p>{a2}</p></details>'

    # 첫 번째 details 이후에 나오는 두 번째 details를 교체
    # faq-section 안의 모든 details를 찾아서 2번째를 교체
    def replace_faq_second(content):
        faq_match = re.search(
            r'(<div class="faq-section">.*?<h2>.*?</h2>)'
            r'(<details>.*?</details>)'   # 1st
            r'(<details>.*?</details>)'   # 2nd  ← replace this
            r'(<details>.*?</details>)',   # 3rd (already JA)
            content, flags=re.DOTALL
        )
        if not faq_match:
            return content, False
        new_content = (
            content[:faq_match.start()]
            + faq_match.group(1)
            + faq_match.group(2)  # 1st (already replaced)
            + f'<details><summary>{q2}</summary><p>{a2}</p></details>'
            + faq_match.group(4)  # 3rd
            + content[faq_match.end():]
        )
        return new_content, True

    content, replaced = replace_faq_second(content)
    if not replaced:
        print(f'  WARN FAQ2 교체 실패: {fname}')

    if content == original:
        print(f'  SKIP (변경없음): {fname}')
        skip += 1
        continue

    with open(fpath, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f'  OK: {fname}')
    ok += 1

print(f'\n완료: {ok}개 업데이트, {skip}개 스킵, {err}개 오류')
